"""Artifact retrieval and compilation endpoints."""

import uuid
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select
from app.db.session import get_db
from app.models.orm import Artifact as ArtifactModel
from app.schemas.artifact import ArtifactResponse, ArtifactCreate

router = APIRouter(prefix="/api/artifacts", tags=["Artifacts"])


@router.get("/{artifact_id}", response_model=ArtifactResponse)
async def get_artifact(artifact_id: str, db: AsyncSession = Depends(get_db)):
    """Retrieves an artifact by ID for display in the Artifact Viewer."""
    res = await db.execute(select(ArtifactModel).where(ArtifactModel.id == artifact_id))
    art = res.scalar_one_or_none()

    if not art:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Artifact '{artifact_id}' not found.",
        )

    return ArtifactResponse(
        id=art.id,
        session_id=art.session_id,
        message_id=art.message_id,
        artifact_type=art.artifact_type,
        title=art.title,
        content=art.content,
        meta_info=art.meta_info,
        created_at=art.created_at,
    )


@router.post("", response_model=ArtifactResponse, status_code=status.HTTP_201_CREATED)
async def create_artifact(req: ArtifactCreate, db: AsyncSession = Depends(get_db)):
    """Explicitly stores an artifact generated by the user or assistant."""
    art_id = str(uuid.uuid4())
    art_record = ArtifactModel(
        id=art_id,
        session_id=req.session_id,
        message_id=req.message_id,
        artifact_type=req.artifact_type,
        title=req.title,
        content=req.content,
        meta_info=req.meta_info or {},
    )
    db.add(art_record)
    await db.commit()
    await db.refresh(art_record)

    return ArtifactResponse(
        id=art_record.id,
        session_id=art_record.session_id,
        message_id=art_record.message_id,
        artifact_type=art_record.artifact_type,
        title=art_record.title,
        content=art_record.content,
        meta_info=art_record.meta_info,
        created_at=art_record.created_at,
    )
